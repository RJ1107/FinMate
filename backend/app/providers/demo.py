def _sector(
    name: str,
    change: float,
    rows: list[tuple],
    news: tuple[str, str],
) -> SectorSnapshot:
    stocks = [
        StockQuote(
            symbol=row[0],
            name=row[1],
            sector=name,
            price=row[2],
            change_percent=row[3],
            turnover_million_cny=row[4],
            market_cap_billion_cny=row[5],
        )
        for row in rows
    ]
    return SectorSnapshot(
        name=name,
        change_percent=change,
        turnover_billion_cny=round(sum(stock.turnover_million_cny for stock in stocks) / 1000, 2),
        stocks=stocks,
        news=[
            MarketNewsItem(
                news_id=f"DEMO-{rows[0][0]}",
                headline=news[0],
                summary=news[1],
                source="FinMate 演示事件",
                published_at=DEMO_OBSERVED_AT,
            )
        ],
    )
